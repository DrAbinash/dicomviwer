#!/usr/bin/env node
/**
 * license-gen-keys.mjs - ONE-TIME vendor setup for the trial licensing system.
 *
 * Generates an Ed25519 signing keypair:
 *   license-admin/private.pem   -> NEVER commit, ships only in the vendor kit zip
 *   license-admin/public.pem    -> convenience copy for the kit README
 *   src/lib/server/license-public.ts -> embedded in the app (safe to be public)
 *
 * Run again ONLY if you want to invalidate every previously issued key
 * (the new public key is compiled into the next build).
 *
 * Usage: node scripts/license-gen-keys.mjs
 */
import { generateKeyPairSync } from "node:crypto";
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ADMIN = join(ROOT, "license-admin");

mkdirSync(ADMIN, { recursive: true });

const { publicKey, privateKey } = generateKeyPairSync("ed25519");

const privPem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();
const pubPem = publicKey.export({ type: "spki", format: "pem" }).toString();
// raw SPKI DER, standard base64 - embedded into the app bundle
const pubDerB64 = publicKey.export({ type: "spki", format: "der" }).toString("base64");

writeFileSync(join(ADMIN, "private.pem"), privPem, { mode: 0o600 });
writeFileSync(join(ADMIN, "public.pem"), pubPem);

const tsFile = `// AUTO-GENERATED by scripts/license-gen-keys.mjs - DO NOT EDIT BY HAND.
// Ed25519 public key (SPKI/DER, base64) that verifies trial license keys.
// The matching PRIVATE key lives in the vendor kit (license-admin/) and is
// never committed to git. Rotate by re-running the generator + rebuilding.

export const LICENSE_PUBLIC_SPKI_B64 =
  "${pubDerB64}";
`;
writeFileSync(join(ROOT, "src/lib/server/license-public.ts"), tsFile);

console.log("Ed25519 license keypair generated.");
console.log("  private : license-admin/private.pem   (keep secret, gitignored)");
console.log("  public  : license-admin/public.pem");
console.log("  embedded: src/lib/server/license-public.ts");
